"""Run pytest with dummy configuration, no dotenv reads and no service connections.

Usage: python scripts/test_offline.py [pytest arguments]
This runner is deliberately separate from conftest so real integration tests can
still be run explicitly in a provisioned development environment.
"""

import os
import sys
import tempfile
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)
# Discard credentials inherited from the terminal before loading application code.
test_path = os.defpath
os.environ.clear()
os.environ.update(
    PATH=test_path,
    PYTHON_DOTENV_DISABLED="1",
    MAPIT_OFFLINE_TESTS="1",
    DATABASE_URL="postgresql://dummy:dummy@127.0.0.1:1/dummy",
    SUPABASE_URL="http://127.0.0.1:1",
    SUPABASE_SERVICE_KEY="dummy-offline-service-key",
    GEMINI_API_KEY="dummy-offline-gemini-key",
    REDIS_URL="redis://127.0.0.1:1/0",
    NEO4J_URI="bolt://127.0.0.1:1",
    NEO4J_USER="dummy",
    NEO4J_PASSWORD="dummy",
    SKIP_LIVE_API_TESTS="1",
)

import pytest


def offline(*args, **kwargs):
    raise OSError("External service connections are disabled by scripts/test_offline.py")


def guard_subprocess(event, arguments):
    if event == "subprocess.Popen":
        executable = Path(os.fsdecode(arguments[0])).resolve()
        # Only our synthetic test CLI may execute. Its source is generated by the
        # adapter fixture; real Codex, Docker, shell commands and service CLIs are blocked.
        if executable.name == "fake-codex" and Path(tempfile.gettempdir()) in executable.parents:
            return
        if Path(tempfile.gettempdir()) in executable.parents and not executable.exists():
            # Missing-executable lifecycle tests must reach the operating system's
            # FileNotFoundError path. There is no executable to run here.
            return
        raise OSError("External subprocesses are disabled by scripts/test_offline.py")
    if event in {"os.system", "os.posix_spawn", "os.exec", "os.spawn"}:
        raise OSError("External subprocesses are disabled by scripts/test_offline.py")


sys.addaudithook(guard_subprocess)


with (
    patch("dotenv.load_dotenv", return_value=False),
    patch("dotenv.dotenv_values", return_value={}),
    patch("pydantic_settings.sources.DotEnvSettingsSource._read_env_files", return_value={}),
    patch("socket.socket.connect", offline),
    patch("socket.socket.connect_ex", offline),
    patch("socket.create_connection", offline),
    patch("psycopg2.connect", offline),
    # gRPC's C transport bypasses Python socket guards.
    patch("google.generativeai.GenerativeModel.generate_content", side_effect=offline),
    patch("google.generativeai.GenerativeModel.generate_content_async", side_effect=offline),
    patch("google.generativeai.embed_content", side_effect=offline),
    patch("google.generativeai.embed_content_async", side_effect=offline),
    patch("google.generativeai.list_models", side_effect=offline),
    # Native framework clients use HTTPX2; cover its transport as well as sockets.
    patch("httpx2.Client.send", side_effect=offline),
    patch("httpx2.AsyncClient.send", side_effect=offline),
):
    raise SystemExit(pytest.main(sys.argv[1:]))
